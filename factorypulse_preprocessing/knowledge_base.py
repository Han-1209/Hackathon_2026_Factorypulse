def get_fault_info(fault_code: str) -> dict:
    """回傳故障資訊。一定會包含所有欄位（缺的補空值），
    這樣呼叫端不用到處寫 .get(..., []) 防呆。"""
    info = FAULT_INFO.get(fault_code)
    if info is None:
        return {**_EMPTY,
                "display": fault_code,
                "description": "未知故障類型，知識庫尚未收錄。",
                "checks": ["請人工複檢"], "actions": ["請人工複檢"]}
    return {**_EMPTY, **info}
